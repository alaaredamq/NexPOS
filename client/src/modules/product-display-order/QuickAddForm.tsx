import { useEffect, useMemo, useState } from 'react'
import { useForm, useWatch } from 'react-hook-form'
import { useTranslation } from 'react-i18next'
import { z } from 'zod'
import { isApiError } from '@/api/http'
import { Button } from '@/ui/Button'
import { FormError } from '@/ui/form/FormError'
import { MoneyField } from '@/ui/form/MoneyField'
import { NumberField } from '@/ui/form/NumberField'
import { SelectField } from '@/ui/form/SelectField'
import { SwitchField } from '@/ui/form/SwitchField'
import { TextField } from '@/ui/form/TextField'
import { applyServerErrors } from '@/ui/form/serverErrors'
import { ModalBody, ModalFooter } from '@/ui/Modal'
import { toast } from '@/ui/toast'
import { zodResolver } from '../_shared/zodResolver'
import { useQuickAdd, useQuickAddOptions } from './api'
import styles from './displayOrder.module.css'

interface FormValues {
  name: string
  description: string
  autoBarcode: boolean
  barcode: string
  price: number | null
  currencyId: number | null
  stockQuantity: number | null
}

interface Props {
  onCancel: () => void
  onDone: () => void
}

/** Creates a basic product and puts it on the main screen in one step (the old "Quick Add" tab). */
export function QuickAddForm({ onCancel, onDone }: Props) {
  const { t } = useTranslation('productDisplayOrder')
  const options = useQuickAddOptions()
  const quickAdd = useQuickAdd()
  const [formErrors, setFormErrors] = useState<string[]>([])

  const schema = useMemo(
    () =>
      z.object({
        name: z.string().refine((v) => v.trim().length > 0, t('ProductNameIsRequired')),
        description: z.string(),
        autoBarcode: z.boolean(),
        barcode: z.string(),
        price: z.number({ error: t('PriceMustBeGreaterThan0') }).gt(0, t('PriceMustBeGreaterThan0')),
        currencyId: z.number().nullable(),
        stockQuantity: z.number().min(0).nullable(),
      }),
    [t],
  )

  const form = useForm<FormValues>({
    resolver: zodResolver<FormValues>(schema),
    defaultValues: { name: '', description: '', autoBarcode: true, barcode: '', price: null, currencyId: null, stockQuantity: 0 },
  })
  const autoBarcode = useWatch({ control: form.control, name: 'autoBarcode' })
  const chosenCurrency = useWatch({ control: form.control, name: 'currencyId' })

  const currencies = useMemo(
    () => (options.data?.currencies ?? []).map((c) => ({ value: c.id, label: `${c.code} (${c.notation})` })),
    [options.data],
  )
  const defaultCurrencyId = options.data?.defaultCurrencyId ?? 0
  const selectedCurrency = options.data?.currencies.find((c) => c.id === (chosenCurrency ?? defaultCurrencyId))

  // Start on the shop's default currency as soon as the list is known.
  useEffect(() => {
    if (defaultCurrencyId && form.getValues('currencyId') === null) form.setValue('currencyId', defaultCurrencyId)
  }, [defaultCurrencyId, form])

  const submit = form.handleSubmit(async (values) => {
    setFormErrors([])
    try {
      const result = await quickAdd.mutateAsync({
        name: values.name.trim(),
        description: values.description.trim() || null,
        barcode: values.autoBarcode ? null : values.barcode.trim() || null,
        generateBarcode: values.autoBarcode,
        price: values.price ?? 0,
        currencyId: values.currencyId ?? defaultCurrencyId,
        stockQuantity: values.stockQuantity ?? 0,
      })
      toast.success(`${t('ProductCreatedAndAdded')} (${t('Barcode')}: ${result.barcode})`)
      onDone()
    } catch (error) {
      setFormErrors(isApiError(error) ? applyServerErrors(form, { errors: error.errors, detail: error.message }) : [t('AnErrorOccurredWhileCreatingTheProduct')])
    }
  })

  return (
    <form onSubmit={submit} noValidate>
      <ModalBody>
        <div className={styles.form}>
          <FormError messages={formErrors} />
          <TextField<FormValues> control={form.control} name="name" label={t('ProductName')} placeholder={t('EnterProductName')} required autoFocus maxLength={200} />
          <TextField<FormValues> control={form.control} name="description" label={t('Description')} placeholder={t('EnterProductDescription')} multiline rows={2} maxLength={500} />
          <div className={styles.pair}>
            <TextField<FormValues>
              control={form.control}
              name="barcode"
              label={t('Barcode')}
              placeholder={autoBarcode ? t('WillBeAutoGenerated') : t('EnterBarcodeManually')}
              hint={t('LeaveEmptyOrCheckBelow')}
              disabled={autoBarcode}
              dir="ltr"
              maxLength={50}
            />
            <SwitchField<FormValues> control={form.control} name="autoBarcode" label={t('AutoGenerate')} />
          </div>
          <div className={styles.row3}>
            <MoneyField<FormValues> control={form.control} name="price" label={t('Price')} required currency={selectedCurrency?.notation} />
            <SelectField<FormValues, number> control={form.control} name="currencyId" label={t('Currency')} options={currencies} />
            <NumberField<FormValues> control={form.control} name="stockQuantity" label={t('StockQuantity')} min={0} decimals={3} />
          </div>
          <p className={styles.note}>
            <strong>{t('QuickAdd')}:</strong> {t('QuickAddInfo')}
          </p>
        </div>
      </ModalBody>
      <ModalFooter>
        <Button variant="ghost" onClick={onCancel} disabled={quickAdd.isPending}>
          {t('Cancel')}
        </Button>
        <Button type="submit" variant="primary" loading={quickAdd.isPending}>
          {t('CreateAndAddProduct')}
        </Button>
      </ModalFooter>
    </form>
  )
}
