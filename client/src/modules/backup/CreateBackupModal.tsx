import { useState } from 'react'
import { useForm } from 'react-hook-form'
import { useTranslation } from 'react-i18next'
import { isApiError } from '@/api/http'
import { Button } from '@/ui/Button'
import { FormError } from '@/ui/form/FormError'
import { TextField } from '@/ui/form/TextField'
import { Loader } from '@/ui/Loader'
import { Modal, ModalBody, ModalFooter } from '@/ui/Modal'
import { toast } from '@/ui/toast'
import { useCreateBackup } from './api'
import styles from './backup.module.css'

interface FormValues {
  name: string
  description: string
}

/**
 * "Create backup". The request returns when the snapshot is written, so the dialog stays up (and cannot be dismissed) with a busy line
 * until then - the Razor page showed a progress modal for the same wait. A failed snapshot is recorded in the list and answers with the reason.
 */
export function CreateBackupModal({ onClose }: { onClose: () => void }) {
  const { t } = useTranslation('backup')
  const create = useCreateBackup()
  const [formErrors, setFormErrors] = useState<string[]>([])
  const form = useForm<FormValues>({ defaultValues: { name: '', description: '' } })

  const submit = form.handleSubmit(async (values) => {
    setFormErrors([])
    try {
      await create.mutateAsync({ name: values.name.trim() || undefined, description: values.description.trim() || undefined })
      toast.success(t('Msg_BackupCompleted'))
      onClose()
    } catch (error) {
      setFormErrors([isApiError(error) || error instanceof Error ? error.message : t('FailedToCreateBackup')])
    }
  })

  return (
    <Modal onClose={create.isPending ? () => {} : onClose} width={520} title={t('CreateNewBackup')} hideClose={create.isPending}>
      <form onSubmit={submit} noValidate>
        <ModalBody>
          <div className={styles.form}>
            <FormError messages={formErrors} />
            <TextField<FormValues>
              control={form.control}
              name="name"
              label={t('BackupName')}
              hint={t('DefaultNameAutoGenerated')}
              placeholder={t('EnterBackupName')}
              maxLength={200}
              autoComplete="off"
              autoFocus
              disabled={create.isPending}
            />
            <TextField<FormValues> control={form.control} name="description" label={t('Description')} multiline rows={2} maxLength={1000} disabled={create.isPending} />
            {create.isPending && (
              <div className={styles.busy} role="status">
                <Loader size="sm" tone="primary" />
                <span>{t('Busy_Creating')}</span>
              </div>
            )}
          </div>
        </ModalBody>
        <ModalFooter>
          <Button variant="ghost" onClick={onClose} disabled={create.isPending}>
            {t('Cancel')}
          </Button>
          <Button type="submit" variant="primary" loading={create.isPending}>
            {t('CreateBackup')}
          </Button>
        </ModalFooter>
      </form>
    </Modal>
  )
}
